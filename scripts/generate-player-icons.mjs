import { readFileSync, writeFileSync } from 'node:fs';

// Bundle only the required Lucide geometry; players do not load React or remote icons.
const bundles = [
  {
    output: '../player/web/weather-icons.js',
    exportName: 'weatherIcons',
    names: [
      'sun',
      'moon',
      'cloud-sun',
      'cloud-moon',
      'cloud',
      'cloudy',
      'cloud-fog',
      'haze',
      'cloud-drizzle',
      'cloud-rain',
      'cloud-rain-wind',
      'cloud-lightning',
      'cloud-snow',
      'cloud-hail',
      'wind',
      'tornado',
      'circle-question-mark',
    ],
  },
  {
    output: '../player/setup-web/recovery-icons.js',
    exportName: 'recoveryIcons',
    names: ['grip-vertical', 'trash-2'],
  },
];
const license = readFileSync(
  new URL('../node_modules/lucide-react/LICENSE', import.meta.url),
  'utf8',
);
for (const { output, exportName, names } of bundles) {
  const icons = {};
  for (const name of names) {
    const { __iconNode } = await import(
      `../node_modules/lucide-react/dist/esm/icons/${name}.mjs`
    );
    icons[name] = __iconNode.map(([tag, { key: _key, ...attributes }]) => [
      tag,
      attributes,
    ]);
  }
  writeFileSync(
    new URL(output, import.meta.url),
    `/* Generated by scripts/generate-player-icons.mjs.\n${license}\n*/\nexport const ${exportName} = ${JSON.stringify(icons, null, 2)};\n`,
  );
}
