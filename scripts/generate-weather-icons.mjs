import { readFileSync, writeFileSync } from 'node:fs';

// Bundle only the required Lucide geometry; players do not load React or remote icons.
const names = [
  'sun',
  'moon',
  'cloud-sun',
  'cloud-moon',
  'cloud',
  'cloudy',
  'cloud-fog',
  'haze',
  'cloud-drizzle',
  'cloud-rain',
  'cloud-rain-wind',
  'cloud-lightning',
  'cloud-snow',
  'cloud-hail',
  'wind',
  'tornado',
  'circle-question-mark',
];
const icons = {};
for (const name of names) {
  const { __iconNode } = await import(
    `../node_modules/lucide-react/dist/esm/icons/${name}.mjs`
  );
  icons[name] = __iconNode.map(([tag, { key: _key, ...attributes }]) => [
    tag,
    attributes,
  ]);
}
const license = readFileSync(
  new URL('../node_modules/lucide-react/LICENSE', import.meta.url),
  'utf8',
);
writeFileSync(
  new URL('../player/web/weather-icons.js', import.meta.url),
  `/* Generated by scripts/generate-weather-icons.mjs.\n${license}\n*/\nexport const weatherIcons = ${JSON.stringify(icons, null, 2)};\n`,
);
