import { readFileSync, writeFileSync } from 'node:fs';

const icons = {};
for (const name of ['grip-vertical', 'trash-2']) {
  const { __iconNode } = await import(
    `../node_modules/lucide-react/dist/esm/icons/${name}.mjs`
  );
  icons[name] = __iconNode.map(([tag, { key: _key, ...attributes }]) => [
    tag,
    attributes,
  ]);
}
const license = readFileSync(
  new URL('../node_modules/lucide-react/LICENSE', import.meta.url),
  'utf8',
);
writeFileSync(
  new URL('../player/setup-web/recovery-icons.js', import.meta.url),
  `/* Generated by scripts/generate-recovery-icons.mjs.\n${license}\n*/\nexport const recoveryIcons = ${JSON.stringify(icons, null, 2)};\n`,
);
